(()=>{
'use strict';
const $=id=>document.getElementById(id);
const links=[...document.querySelectorAll('.primary-side-link')];
function closeMobile(){ $('sidebar').classList.remove('open');$('scrim').classList.remove('show'); }
function navigate(view,opts={}){
 const isHome=view==='dashboard',isCourse=view==='course',isPractice=view==='practice',isExams=view==='exams',isLesson=view==='lesson';
 $('homeHero').hidden=!isHome;$('statsGrid').hidden=!isHome;
 $('curriculum').hidden=!(isCourse||isHome);
 $('lessonView').hidden=!isLesson;
 $('practiceHub').hidden=!isPractice;$('examHub').hidden=!isExams;
 links.forEach(b=>b.classList.toggle('active',b.dataset.view===view||(isLesson&&b.dataset.view==='course')));
 if(!opts.keepScroll){const target=isHome?$('homeHero'):isCourse?$('curriculum'):isPractice?$('practiceHub'):isExams?$('examHub'):$('lessonView');target?.scrollIntoView({behavior:'smooth',block:'start'});}
 if(opts.closeMobile!==false)closeMobile();
}
window.HJSNavigate=navigate;
$('dashboardNav').addEventListener('click',()=>navigate('dashboard'));
$('courseNav').addEventListener('click',()=>navigate('course'));
$('exploreCourseLink').addEventListener('click',()=>navigate('course'));
$('practiceNav').addEventListener('click',()=>navigate('practice'));
$('examNav').addEventListener('click',()=>navigate('exams'));
// Lesson buttons are generated by app.js. Use delegation so regenerated items stay functional.
$('lessonNav').addEventListener('click',e=>{if(e.target.closest('[data-id]')){links.forEach(b=>b.classList.toggle('active',b.dataset.view==='course'));closeMobile();}});
// Any lesson opened from a card or sidebar should have a consistent, exclusive view.
const originalScrollTo=window.scrollTo.bind(window);
$('startBtn').addEventListener('click',()=>{links.forEach(b=>b.classList.toggle('active',b.dataset.view==='course'));closeMobile();});
// Default visible state after login.
navigate('dashboard',{keepScroll:true,closeMobile:false});
})();
